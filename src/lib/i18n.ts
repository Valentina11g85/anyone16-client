export type TranslationKey = keyof (typeof dictionaries)["es"];

/** Languages offered in the UI; those without a dictionary fall back to Spanish. */
export type SupportedLanguage = keyof typeof dictionaries;

export type Translator = (key: TranslationKey) => string;

export function createTranslator(languageCode: string): Translator {
  const dictionary =
    (dictionaries as Record<string, Partial<Record<TranslationKey, string>>>)[languageCode] ??
    dictionaries.es;
  return (key) => dictionary[key] ?? dictionaries.es[key] ?? key;
}

