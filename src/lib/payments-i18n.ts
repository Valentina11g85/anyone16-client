const dictionaries: Record<string, Record<string, string>> = { es, en };

export type PayKey = keyof typeof es;
export type PayTranslator = (key: PayKey) => string;

export function createPayTranslator(languageCode: string): PayTranslator {
  const dictionary = dictionaries[languageCode] ?? es;
  return (key) => dictionary[key] ?? es[key] ?? key;
}
